#!/usr/bin/env python3
"""mktour.py OUT.s - a walk that eats every dot, for the AUTOTOUR test build.

Uses the maze exactly as tools/mkmaze.py defines it (open cells, dots,
tunnel). The walk goes to the nearest uneaten dot again and again, then
crosses the tunnel both ways. Output: tour_table, one direction byte per
cell left (0 right, 1 left, 2 up, 3 down), $FF at the end. tour_table eats
every dot; tour_table2 is walked on the next board (tunnel both ways). The autopilot in
maze.s takes the next byte each time Pac-Man reaches a new cell centre, so a
corridor that does not really let him through shows up as a tour that never
finishes.
"""
import contextlib
import io
import os
import runpy
import sys
from collections import deque

HERE = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
sys.argv = ["mkmaze.py", os.devnull]
with contextlib.redirect_stdout(io.StringIO()):
    g = runpy.run_path(os.path.join(HERE, "mkmaze.py"))
typ, dots, pac = g["typ"], g["dots"], g["pac"]
TUN_ROW, TL, TR = g["tunnel_row"], g["tunnel_cols"][0], g["tunnel_cols"][1]
H, W = len(typ), len(typ[0])
DIRS = ((0, 1), (0, -1), (-1, 0), (1, 0))      # right left up down


def moves(cell):
    r, c = cell
    for d, (dr, dc) in enumerate(DIRS):
        n = (r + dr, c + dc)
        if 0 <= n[0] < H and 0 <= n[1] < W and typ[n[0]][n[1]] in (0, 4):
            yield d, n
    if cell == (TUN_ROW, TL):
        yield 1, (TUN_ROW, TR)                 # left out of the tunnel wraps
    if cell == (TUN_ROW, TR):
        yield 0, (TUN_ROW, TL)


def path_to(start, goals):
    prev, q = {start: None}, deque([start])
    while q:
        cur = q.popleft()
        if cur in goals and cur != start:
            seq = []
            while prev[cur]:
                cur, d = prev[cur]
                seq.append((cur, d))
            return seq[::-1]
        for d, n in moves(cur):
            if n not in prev:
                prev[n] = (cur, d)
                q.append(n)
    return None


todo = {(r, c) for r in range(H) for c in range(W) if dots[r][c]}
cur = tuple(pac)
todo.discard(cur)
table = []
while todo:
    steps = path_to(cur, todo)
    assert steps, "dots left that no path reaches: %s" % sorted(todo)
    for cell, d in steps:
        table.append(d)
        nxt = [n for dd, n in moves(cell) if dd == d][0]
        todo.discard(nxt)
        cur = nxt
table.append(0xFF)
# second board (after the clear Pac-Man is back at the start): out through
# the tunnel mouth on the left, back through the one on the right
cur = tuple(pac)
table2 = []
for goal, d in (((TUN_ROW, TL), 1), ((TUN_ROW, TR), 0)):
    steps = path_to(cur, {goal}) or []
    for cell, dd in steps:
        table2.append(dd)
        cur = [n for x, n in moves(cell) if x == dd][0]
    table2.append(d)                           # step into the mouth: wraps
    cur = [n for x, n in moves(cur) if x == d][0]
table2.append(0xFF)
with open(out, "w") as f:
    f.write("; generated by tools/mktour.py - do not edit\n")
    f.write('.segment "RODATA"\n')
    for name, t in (("tour_table", table), ("tour_table2", table2)):
        f.write(name + ":\n")
        for i in range(0, len(t), 20):
            f.write("  .byte " + ",".join("$%02X" % b for b in t[i:i + 20]) + "\n")
print("mktour: %d moves for %d dots, %d moves for the tunnel" % (len(table) - 1, sum(map(sum, dots)), len(table2) - 1))
